CREATE SEQUENCE IF NOT EXISTS account_id_sequence
    START WITH 10000000001
    INCREMENT BY 1
    MINVALUE 10000000001
    MAXVALUE 99999999999
    NO CYCLE;

CREATE SEQUENCE IF NOT EXISTS account_number_sequence
    START WITH 100000000001
    INCREMENT BY 1
    MINVALUE 100000000001
    MAXVALUE 999999999999999999
    NO CYCLE;
